def write_csv(category: str, messages: list[str], output_dir: str):
    filename = os.path.join(output_dir, f'synthetic_{category}.csv')
    with open(filename, 'w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['text', 'category', 'is_obfuscated'])
        for msg in messages:
            writer.writerow([msg, category, 0])
    print(f"  ✅ synthetic_{category}.csv — {len(messages)} examples")

def main():
    output_dir = os.path.dirname(os.path.abspath(__file__))
    print(f"Writing synthetic CSVs to: {output_dir}\n")
    for category, messages in DATA.items():
        write_csv(category, messages, output_dir)
    total = sum(len(v) for v in DATA.values())
    print(f"\n✅ Done — {total} total synthetic examples across {len(DATA)} categories")

if __name__ == '__main__':
    main()
